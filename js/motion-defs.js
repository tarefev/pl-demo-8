/** Прилагательное женского рода в винительный падеж: «судебно-медицинская» → «судебно-медицинскую». */
function femAcc(s) {
  return String(s || '').replace(/ая$/, 'ую').replace(/яя$/, 'юю');
}

/** Срок отложения в просительную часть: «на десять суток», «на срок не менее пяти суток». */
function postponeTerm(t) {
  if (!t) return mMark('указать срок');
  const s = String(t).trim().toLowerCase();
  return /^на\s/.test(s) ? s : `на срок ${s}`;
}

/** Свободный текст адвоката абзацем: точка в конце либо жёлтая метка. */
function mText(v, ph) {
  return v && String(v).trim() ? endDot(v) : mMark(ph);
}

/** Точка в конце фразы, введённой адвокатом вручную. */
function endDot(s) {
  const t = String(s || '').trim();
  return t && !/[.!?;:]$/.test(t) ? t + '.' : t;
}

/** Мера пресечения в нужном падеже: 'gen' — родительный, 'acc' — винительный. */
function measureForm(m, form, ph) {
  if (!m) return mMark(ph || 'указать меру');
  const pair = MEASURE_FORMS[m];
  if (!pair) return String(m).toLowerCase();
  return form === 'acc' ? pair[1] : pair[0];
}

