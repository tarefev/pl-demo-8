      body.push(mText(ctx.answers.why, 'изложить обоснование необходимости экспертизы'));
      if (t === 'Дополнительная') body.push('Заключение эксперта является недостаточно ясным и полным.', NQ.art207_1);
      if (t === 'Повторная') body.push('Обоснованность заключения эксперта вызывает сомнения, в выводах имеются противоречия.', NQ.art207_2);
      if (ctx.stage !== 'court') body.push(NQ.art195);
      body.push(NQ.art198_1, NQ.art159_2);

      const plea = [
        `Назначить по уголовному делу ${c.num} ${!t || t === 'Первичная' ? 'судебную ' : femAcc(t.toLowerCase()) + ' судебную '}${kind ? femAcc(kind.toLowerCase()) : mMark('указать вид')} экспертизу.`
      ];
      if (org) plea.push(`Производство экспертизы поручить ${org}.`);
      // в типовых вопросах есть подстановки вида {лицо}, {документ} — просим адвоката уточнить
      const fillQ = q => String(q).replace(/\{([^}]+)\}/g, (_, n) => mMark(`указать ${n}`));
      plea.push(qs.length
        ? `Поставить перед экспертом следующие вопросы:<br>${qs.map((q, i) => `${i + 1}) ${fillQ(q)}`).join('<br>')}`
        : mMark('указать вопросы эксперту'));
      if (ctx.answers.challenge) plea.push('Заявить отвод эксперту, проводившему первичную экспертизу.');
      plea.push(`Предоставить защитнику и ${clientRole(ctx, 'dat')} возможность ознакомиться с постановлением о назначении экспертизы до её производства, а также с заключением эксперта по её завершении.`);
