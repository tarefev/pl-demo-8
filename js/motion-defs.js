/**
 * Определения ходатайств: шаги визарда и сборка документа.
 *
 * Каждое ходатайство описано декларативно:
 *   title(ctx)  — наименование документа
 *   steps[]     — шаги визарда (см. типы ниже)
 *   build(ctx)  — сборка: мотивировка, просительная часть, приложения, нормы, чеклист
 *
 * Типы шагов:
 *   choice       — выбрать один вариант
 *   choice-group — выбрать один из двухуровневого списка
 *   multi        — выбрать несколько
 *   multi-group  — выбрать несколько из двухуровневого списка
 *   text         — свободный текст
 *   form         — набор полей
 *   evidence     — доказательство из карточки дела или новое
 *   confirm      — подтверждение (обязательная отметка)
 */

/** Жёлтая метка «не заполнено» в тексте документа. */
const mMark = t => `<span class="ph-mark">${t}</span>`;
/** Значение или метка, если пусто. */
const mVal = (v, ph) => (v && String(v).trim() ? String(v).trim() : mMark(ph));

/** Данные дела для подстановки в текст. */
function motionCase() {
  const c = state.card;
  const court = c.court || {};
  return {
    num: court.caseNum ? `№ ${court.caseNum}` : mMark('указать номер дела'),
    client: c.clientGen || c.client || mMark('указать ФИО доверителя'),
    clientNom: c.client || mMark('указать ФИО доверителя'),
    clientDat: c.clientDat || c.client || mMark('указать ФИО доверителя'),
    // орган расследования без ведущего предлога — он подставляется по месту
    org: (c.investigatorOrg || '').replace(/^В\s+/, '') || null,
    qual: (c.episodes[0] && c.episodes[0].qualification) || mMark('указать квалификацию'),
    firstCourt: court.firstInstanceCourt || court.firstInstance || mMark('указать суд'),
    // родительный падеж для оборота «в производстве …»
    firstCourtGen: court.firstInstanceGen || court.firstInstanceCourt || court.firstInstance || mMark('указать суд'),
    advocate: c.advocate || mMark('указать ФИО защитника'),
    advocateDat: c.advocateDat || c.advocate || mMark('указать ФИО защитника'),
    prosecutorDat: c.prosecutorDat || mMark('указать наименование прокуратуры')
  };
}

/**
 * Вводные абзацы по шаблону: где находится дело и кто осуществляет защиту.
 * opts.charged — «в отношении …, обвиняемого в совершении преступления, предусмотренного …»
 * (иначе — «по признакам преступления, предусмотренного …, в отношении …»).
 */
function motionIntro(ctx, opts) {
  const c = motionCase();
  const card = state.card;
  const org = ctx.stage === 'court'
    ? c.firstCourtGen
    : mVal(c.org || card.investigator, 'указать орган предварительного расследования');
  return [
    (opts && opts.charged)
      ? `В производстве ${org} находится уголовное дело ${c.num} в отношении ${c.client}, обвиняемого в совершении преступления, предусмотренного ${c.qual}.`
      : `В производстве ${org} находится уголовное дело ${c.num} по признакам преступления, предусмотренного ${c.qual}, в отношении ${c.client}.`,
    `Защиту интересов ${c.client} на основании ордера № ${mVal(card.orderNum, 'указать номер ордера')} от ${mVal(card.orderDate, 'указать дату')} и соглашения об оказании юридической помощи осуществляет адвокат ${mVal(card.advocate, 'указать ФИО защитника')}.`
  ];
}

/** Ордер адвоката в перечне приложений. */
function orderAtt() {
  const card = state.card;
  return `Ордер адвоката № ${mVal(card.orderNum, 'номер')} от ${mVal(card.orderDate, 'дата')} — на 1 л. в 1 экз.`;
}

/** Процессуальный статус доверителя: «обвиняемого», «подсудимого», «подозреваемого». */
function clientRole(ctx, form) {
  const s = state.card.clientStatus;
  const base = s && !/осужд/.test(s) ? s.replace(/ого$/, '') : (ctx && ctx.stage === 'court' ? 'подсудим' : 'обвиняем');
  const stem = base.replace(/(ый|ого|ому)$/, '');
  return { nom: stem + 'ый', gen: stem + 'ого', dat: stem + 'ому' }[form || 'gen'];
}

